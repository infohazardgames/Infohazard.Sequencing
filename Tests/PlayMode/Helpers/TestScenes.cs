using System.IO;

namespace Infohazard.Sequencing.Tests.PlayMode {
    /// <summary>
    /// Paths and IDs of the test scenes and their manifest entries. The assets are generated by
    /// <c>SequencingTestSceneGenerator.Generate()</c> in the Editor test assembly; regenerate them after changing
    /// anything here.
    /// </summary>
    public static class TestScenes {
        public const string Folder = "Packages/com.infohazard.sequencing/Tests/PlayMode/Scenes";
        public const string EntryFolder = Folder + "/Manifest";

        /// <summary>
        /// Level with a LevelRoot. Its regions are <see cref="RegionA"/>, <see cref="RegionB"/> and
        /// <see cref="RegionGated"/>.
        /// </summary>
        public const string Level = Folder + "/SeqTest_Level.unity";

        /// <summary>
        /// A second level with a LevelRoot and no regions.
        /// </summary>
        public const string Level2 = Folder + "/SeqTest_Level2.unity";

        /// <summary>
        /// Region of <see cref="Level"/> with a RegionRoot.
        /// </summary>
        public const string RegionA = Folder + "/SeqTest_RegionA.unity";

        /// <summary>
        /// Region of <see cref="Level"/> with a RegionRoot, loaded by default.
        /// </summary>
        public const string RegionB = Folder + "/SeqTest_RegionB.unity";

        /// <summary>
        /// Region of <see cref="Level"/> with a <see cref="TestGatedRegionRoot"/>, whose initialization the test
        /// controls.
        /// </summary>
        public const string RegionGated = Folder + "/SeqTest_RegionGated.unity";

        /// <summary>
        /// A scene that isn't a level or region. Contains a GameObject named <see cref="PlainMarker"/>.
        /// </summary>
        public const string Plain = Folder + "/SeqTest_Plain.unity";

        public const string PlainMarker = "PlainMarker";

        /// <summary>
        /// Level with a PersistedLevelRoot and static persisted objects (see the object name constants).
        /// Its regions are <see cref="PRegionA"/> and <see cref="PRegionB"/>.
        /// </summary>
        public const string PLevel = Folder + "/SeqTest_PLevel.unity";

        /// <summary>
        /// Region of <see cref="PLevel"/> with a PersistedRegionRoot, <see cref="RegionACrate"/> and
        /// <see cref="Mover"/>.
        /// </summary>
        public const string PRegionA = Folder + "/SeqTest_PRegionA.unity";

        /// <summary>
        /// Region of <see cref="PLevel"/> with a PersistedRegionRoot and <see cref="RegionBCrate"/>.
        /// </summary>
        public const string PRegionB = Folder + "/SeqTest_PRegionB.unity";

        public const int PLevelID = 9101;
        public const int PRegionAID = 21;
        public const int PRegionBID = 22;

        // Static persisted objects in PLevel.

        /// <summary>PersistedTransform (with scale), PersistedComponentEnabled targeting its TestToggle.</summary>
        public const string StaticCrate = "StaticCrate";

        /// <summary>Non-kinematic Rigidbody without gravity, and a PersistedRigidbody.</summary>
        public const string StaticBall = "StaticBall";

        /// <summary>Only a PersistedGameObject.</summary>
        public const string StaticDestroyable = "StaticDestroyable";

        /// <summary>RememberCurrentRegion with <see cref="PRegionA"/> as its initial region.</summary>
        public const string Rememberer = "Rememberer";

        /// <summary>Converts to a dynamic instance immediately, but has no prefab reference. Inactive.</summary>
        public const string BadConverter = "BadConverter";

        /// <summary>
        /// Converts to a dynamic instance immediately, with prefab <see cref="ConverterPrefabKey"/>. Inactive.
        /// </summary>
        public const string GoodConverter = "GoodConverter";

        // Static persisted objects in the persisted regions.

        /// <summary>In <see cref="PRegionA"/>, with a PersistedTransform.</summary>
        public const string RegionACrate = "RegionACrate";

        /// <summary>In <see cref="PRegionB"/>, with a PersistedTransform.</summary>
        public const string RegionBCrate = "RegionBCrate";

        /// <summary>
        /// In <see cref="PRegionA"/>: CanMoveBetweenRegions, PersistedTransform, prefab <see cref="MoverPrefabKey"/>.
        /// </summary>
        public const string Mover = "Mover";

        /// <summary>
        /// Addressable keys (GUID format, as AssetReference requires) that tests register in-memory prefabs under.
        /// </summary>
        public const string MoverPrefabKey = "c0ffee00c0ffee00c0ffee00c0ff0001";

        public const string ConverterPrefabKey = "c0ffee00c0ffee00c0ffee00c0ff0002";

        public const int LevelID = 9001;
        public const int Level2ID = 9002;
        public const int RegionAID = 1;
        public const int RegionBID = 2;
        public const int RegionGatedID = 3;

        public static readonly string[] AllScenes = {
            Level, Level2, RegionA, RegionB, RegionGated, Plain, PLevel, PRegionA, PRegionB,
        };

        /// <summary>
        /// Path of the manifest entry asset for a scene.
        /// </summary>
        public static string EntryPath(string scenePath) =>
            $"{EntryFolder}/{Path.GetFileNameWithoutExtension(scenePath)}.asset";

        /// <summary>
        /// Scene name (what SceneLoadingManager keys scenes by).
        /// </summary>
        public static string Name(string scenePath) => Path.GetFileNameWithoutExtension(scenePath);
    }
}
